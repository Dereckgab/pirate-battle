// Converts the Starling/Sparrow XML atlas shipped with the challenge assets into a typed
// frame table consumed by the PixiJS asset loader. Run with `npm run atlas`.
import { readFileSync, writeFileSync } from 'node:fs'

const xml = readFileSync('public/assets/spritesheet/ships_miscellaneous_sheet.xml', 'utf8')
const frames = {}
for (const match of xml.matchAll(
  /<SubTexture name="([^"]+)\.png" x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"\/>/g,
)) {
  const [, name, x, y, w, h] = match
  frames[name] = [Number(x), Number(y), Number(w), Number(h)]
}

const names = Object.keys(frames).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
const body = names.map((name) => `  ${name}: [${frames[name].join(', ')}],`).join('\n')
writeFileSync(
  'src/game/render/shipAtlasFrames.ts',
  `// Generated by scripts/convert-atlas.mjs from ships_miscellaneous_sheet.xml. Do not edit.\n` +
    `export const SHIP_ATLAS_FRAMES = {\n${body}\n} as const satisfies Record<string, readonly [number, number, number, number]>\n\n` +
    `export type ShipAtlasFrame = keyof typeof SHIP_ATLAS_FRAMES\n`,
)
console.log(`Wrote ${names.length} frames`)
